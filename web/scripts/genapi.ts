// Generates the owner API's TypeScript types from the JSON Schema that
// internal/protocol exports (AGENTS.md §3). Run with `pnpm gen` after
// `make gen` changes the schema; genapi.test.ts fails while the committed
// types are out of date.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { compile, type JSONSchema } from "json-schema-to-typescript";

const here = (p: string): string => fileURLToPath(new URL(p, import.meta.url));

/** The committed schema, relative to the repository root. */
export const schemaSource = "internal/protocol/generated/api.schema.json";
export const schemaPath = here(`../../${schemaSource}`);
export const outputPath = here("../src/api/generated/api.ts");

const banner = `/* Generated by \`pnpm gen\` (web/scripts/genapi.ts) from ${schemaSource}. Do not edit. */`;

/** Returns the generated source for the committed schema. */
export async function generate(): Promise<string> {
  const schema = JSON.parse(await readFile(schemaPath, "utf8")) as JSONSchema;
  return compile(schema, "TendAPI", {
    bannerComment: banner,
    additionalProperties: false,
    strictIndexSignatures: true,
    unreachableDefinitions: true,
    format: true,
    style: { printWidth: 100 },
  });
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(outputPath, await generate());
}
